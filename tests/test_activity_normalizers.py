"""Activity normalisers against scrubbed real payloads (tests/fixtures/activities)."""

import datetime as dt
import json
from pathlib import Path

from gds.domains import REGISTRY, activity_domains
from gds.domains.activities import activity_row, units_for
from gds.store import TABLE_KEYS, _adapt

FIXTURES = Path(__file__).parent / "fixtures" / "activities"
RUN_ID, STRENGTH_ID, SOCCER_ID = "24742846558", "24660073611", "24448347816"


def load(name: str):
    return json.loads((FIXTURES / f"{name}.json").read_text(encoding="utf-8"))


def norm(domain: str, fixture: str, key: str) -> dict:
    return REGISTRY[domain].normalize(load(fixture), key)


def test_every_activity_table_has_keys():
    for t in ("activities", "activity_laps", "activity_zones", "activity_exercise_sets", "activity_weather",
              "activity_files"):
        assert t in TABLE_KEYS


def test_activity_row_from_list_item():
    run = next(a for a in load("index") if a["activityType"]["typeKey"] == "running")
    row = activity_row(run)
    assert row["activity_id"] == int(RUN_ID)
    assert row["start_utc"] == dt.datetime(2026, 10, 16, 9, 18, 45, tzinfo=dt.UTC)
    assert row["start_local"] == dt.datetime(2026, 10, 16, 11, 18, 45)
    assert row["utc_offset_min"] == 120
    assert round(row["distance_m"]) == 4084 and row["avg_hr"] == 145.0
    assert row["avg_cadence"] == 163.40625
    assert row["te_label"] == "AEROBIC_BASE"
    assert row["hr_zone_s"] == [505.988, 1291.437, 0.0, 0.0, 0.0]
    assert len(row["power_zone_s"]) == 5


def test_index_creates_units_per_activity_and_skips_impossible_ones():
    result = REGISTRY["activity_index"].normalize(load("index"), "recent")
    assert len(result["activities"]) == 3
    by_activity: dict[str, set[str]] = {}
    for u in result["work_units"]:
        by_activity.setdefault(u["scope_key"], set()).add(u["domain"])
    all_names = {d.name for d in activity_domains()}
    run, strength, soccer = by_activity[RUN_ID], by_activity[STRENGTH_ID], by_activity[SOCCER_ID]
    assert run == all_names - {"activity_exercise_sets"}  # outdoor run with power, no sets
    assert "activity_exercise_sets" in strength and "activity_weather" not in strength
    assert "activity_power_zones" not in soccer and "activity_weather" not in soccer  # no power, no GPS


def test_recent_activities_are_requeued():
    run = next(a for a in load("index") if a["activityType"]["typeKey"] == "running")
    row = activity_row(run)
    soon_after = row["start_utc"] + dt.timedelta(hours=5)
    long_after = row["start_utc"] + dt.timedelta(days=30)
    assert all(u["requeue"] for u in units_for(run, row, soon_after))
    assert not any(u["requeue"] for u in units_for(run, row, long_after))


def test_laps():
    laps = norm("activity_laps", "running__laps", RUN_ID)["activity_laps"]
    assert len(laps) >= 1
    assert [lap["lap_index"] for lap in laps] == sorted({lap["lap_index"] for lap in laps})
    assert all(lap["activity_id"] == int(RUN_ID) for lap in laps)
    assert laps[0]["avg_hr"] is not None and laps[0]["start_utc"] is not None


def test_hr_and_power_zones():
    hr = norm("activity_hr_zones", "running__hr_zones", RUN_ID)["activity_zones"]
    assert [z["zone"] for z in hr] == [1, 2, 3, 4, 5]
    assert hr[0]["seconds"] == 505.988 and hr[0]["low_boundary"] == 116 and hr[0]["zone_type"] == "hr"
    power = norm("activity_power_zones", "running__power_zones", RUN_ID)["activity_zones"]
    assert power[0]["zone_type"] == "power" and power[0]["low_boundary"] == 270


def test_exercise_sets_pick_most_likely_exercise():
    sets = norm("activity_exercise_sets", "strength_training__exercise_sets", STRENGTH_ID)["activity_exercise_sets"]
    first = sets[0]
    assert first["set_index"] == 0 and first["reps"] == 9 and first["set_type"] == "ACTIVE"
    assert (first["category"], first["exercise_name"]) == ("HIP_RAISE", "BARBELL_HIP_THRUST_ON_FLOOR")
    assert len(first["candidates"]) == 3


def test_weather_keeps_imperial_values():
    (w,) = norm("activity_weather", "running__weather", RUN_ID)["activity_weather"]
    assert w["temp_f"] == 51 and w["conditions"] == "Cloudy"
    assert w["observed_utc"] == dt.datetime(2026, 10, 16, 9, 0, tzinfo=dt.UTC)
    assert "temp_c" not in w  # generated by the database


def test_gear_is_written_as_json():
    (row,) = norm("activity_gear", "running__gear", RUN_ID)["activities"]
    assert row["gear"][0]["name"] == "ASICS Novablast 6" and row["gear"][0]["type"] == "Shoes"
    assert type(_adapt(row["gear"])).__name__ == "Jsonb"
    assert _adapt([1.0, 2.0]) == [1.0, 2.0]  # scalar lists stay arrays


def test_summary_detail_partial_row():
    (row,) = norm("activity_summary", "running__summary", RUN_ID)["activities"]
    assert set(row) == {"activity_id", "description", "rpe", "feel", "min_hr", "workout_id", "workout_compliance"}


def test_fit_payload_becomes_file_row():
    data = b"PK\x03\x04fake zip"
    (row,) = REGISTRY["activity_fit"].normalize(data, RUN_ID)["activity_files"]
    assert row["bytes"] == len(data) and row["format"] == "original_zip" and len(row["sha256"]) == 64
    assert REGISTRY["activity_fit"].binary


def test_activity_normalizers_tolerate_empty_payloads():
    for d in activity_domains():
        if d.normalize:
            for raw in (None, {}, [], {"unexpected": True}, b""):
                assert isinstance(d.normalize(raw, RUN_ID), dict)
